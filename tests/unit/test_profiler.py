"""Unit tests for perflens.profiler — VTune and HPCToolkit parsers."""

from __future__ import annotations

import textwrap
from pathlib import Path

import pytest

from perflens.profiler.dispatcher import parse_profile
from perflens.profiler.models import Hotspot, ProfileData
from perflens.profiler.vtune_parser import VTuneParser
from perflens.profiler.hpctoolkit_parser import HPCToolkitParser


# ── VTune CSV ─────────────────────────────────────────────────────────────────

VTUNE_CSV_SIMPLE = textwrap.dedent("""\
    Function,Module,CPU Time,CPU Time (%),CPI Rate,L3 Cache Miss Rate,Memory Bound (%)
    compute_flux,libsolver.so,2500.5,45.3,1.82,0.12,62.1
    update_wetcells,libsolver.so,1200.0,21.7,1.21,0.03,18.4
    _start,solver,50.0,0.9,0.95,,
    MPI_Waitall,libmpi.so,800.0,14.5,,,
""")

VTUNE_CSV_WITH_METADATA = textwrap.dedent("""\
    # VTune Profiler Report
    # Report: Hotspots
    # Date: 2025-06-01
    Function (Full),Module,Source File,Start Line,CPU Time (ms),CPI,Vectorization (%),Arithmetic Intensity
    compute_flux,solver,src/solver.c,142,3200.0,1.82,72.4,1.85
    extrapolate_second_order,solver,src/extrapolate.c,87,1800.0,2.14,41.2,0.42
    update_conserved,solver,src/update.c,201,950.0,1.05,88.1,3.21
""")


def _write(tmp_path: Path, name: str, text: str) -> Path:
    p = tmp_path / name
    p.write_text(text)
    return p


def test_vtune_csv_basic(tmp_path):
    csv = _write(tmp_path, "report.csv", VTUNE_CSV_SIMPLE)
    pd = VTuneParser().parse(report_path=csv)
    assert pd.tool == "vtune"
    assert len(pd.hotspots) >= 3
    # Top hotspot should be compute_flux
    top = pd.top_hotspots(1)[0]
    assert "compute_flux" in top.function or top.cpu_time_ms >= 2000


def test_vtune_csv_cpi_parsed(tmp_path):
    csv = _write(tmp_path, "report.csv", VTUNE_CSV_SIMPLE)
    pd = VTuneParser().parse(report_path=csv)
    hotspot = next((h for h in pd.hotspots if "compute_flux" in h.function), None)
    assert hotspot is not None
    assert hotspot.cpi is not None
    assert abs(hotspot.cpi - 1.82) < 0.01


def test_vtune_csv_percentages_sum_approx_100(tmp_path):
    csv = _write(tmp_path, "report.csv", VTUNE_CSV_SIMPLE)
    pd = VTuneParser().parse(report_path=csv)
    total_pct = sum(h.cpu_time_pct for h in pd.hotspots)
    # Should be ~100% (may be slightly off due to rounding/incomplete data)
    assert 80.0 <= total_pct <= 120.0


def test_vtune_csv_with_metadata_header(tmp_path):
    """Parser should skip comment/metadata lines and find the real header."""
    csv = _write(tmp_path, "report2.csv", VTUNE_CSV_WITH_METADATA)
    pd = VTuneParser().parse(report_path=csv)
    assert len(pd.hotspots) >= 2


def test_vtune_csv_arithmetic_intensity(tmp_path):
    csv = _write(tmp_path, "report3.csv", VTUNE_CSV_WITH_METADATA)
    pd = VTuneParser().parse(report_path=csv)
    ai_hotspots = [h for h in pd.hotspots if h.arithmetic_intensity is not None]
    assert len(ai_hotspots) >= 1


def test_vtune_no_report_returns_empty():
    pd = VTuneParser().parse(report_path=None)
    assert pd.total_time_ms == 0.0
    assert pd.hotspots == []


def test_vtune_nonexistent_path_raises(tmp_path):
    with pytest.raises(Exception):
        VTuneParser().parse(report_path=tmp_path / "nonexistent.csv")


