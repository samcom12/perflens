# ── ProfileData model ─────────────────────────────────────────────────────────

def test_profiledata_top_hotspots_sorted():
    pd = ProfileData(
        tool="vtune", source=None, report_path=None, total_time_ms=1000.0,
        hotspots=[
            Hotspot("a", "", None, 0, 10.0, 100.0, None, None, None, None, None, None, None),
            Hotspot("b", "", None, 0, 80.0, 800.0, None, None, None, None, None, None, None),
            Hotspot("c", "", None, 0, 10.0, 100.0, None, None, None, None, None, None, None),
        ],
    )
    top = pd.top_hotspots(2)
    assert top[0].function == "b"
    assert len(top) == 2


def test_profiledata_to_dict():
    import json
    pd = ProfileData(
        tool="vtune", source=None, report_path=None, total_time_ms=5000.0,
        hotspots=[Hotspot("flux", "solver", "solver.c", 142, 60.0, 3000.0,
                          1.8, 0.12, 0.62, 0.15, 0.72, 8.5, 1.85)],
    )
    d = pd.to_dict()
    json.dumps(d)   # must be serialisable
    assert d["total_time_ms"] == 5000.0
    assert len(d["hotspots"]) == 1


def test_hotspot_to_dict():
    h = Hotspot("flux", "solver", "solver.c", 142, 45.3, 2500.5,
                1.82, 0.12, 0.62, 0.18, 0.72, 9.1, 1.85)
    d = h.to_dict()
    assert d["function"] == "flux"
    assert d["cpu_time_ms"] == 2500.5
